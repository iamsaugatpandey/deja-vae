"""E5b follow-up (EXPLORATORY, post hoc: the pre-specified SDXL prediction failed). Which SDXL decoder did Synthbuster use?
Synthbuster's SD2/SDXL images were made with Stability's generative-models code (sampler names in prompts.csv), which
decodes with the autoencoder baked into the checkpoint. Public SDXL autoencoders differ: the base-1.0 repo ships `vae`
(the 0.9 autoencoder, cf. sd_xl_base_1.0_0.9vae.safetensors) and `vae_1_0`; the standalone stabilityai/sdxl-vae (used
in E5b) had its weights updated and reverted (Jul 2023); madebyollin's fp16-fix is a fine-tuned decoder.
Same images, views, layers and score as dv_bank_sb.py; SDXL rows only (+ SD2 as a control generated by the same code).
    anchor/bin/python dv_bank_sdxl.py   -> runs/sb/bank/sdxl_followup.txt
"""
import os, sys, json, time
os.environ.setdefault("DV_FEAT", "mid")
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
import anchor_pilot as ap
import dv_bank_sb as B
from dv_bank_full import view32, auroc

EXTRA = {"sdxl_base_vae": "stabilityai/stable-diffusion-xl-base-1.0:vae",
         "sdxl_base_vae_1_0": "stabilityai/stable-diffusion-xl-base-1.0:vae_1_0",
         "sdxl_fp16fix": "madebyollin/sdxl-vae-fp16-fix"}
GENS = ("stable-diffusion-xl", "stable-diffusion-2")


def main():
    import torch
    G = json.load(open(B.OUT / "groups.json")); keys = [f"{g}:{c}" for g in GENS for c in ("real", "fake")]
    views = {k: [view32(p) for p in G[k]] for k in keys}
    dev = ap.pick_device(); enc = ap.Encoders(dev, need_vae=False, norm="simlbr")

    def cls_layers(ims):
        out = []
        for s in range(0, len(ims), 16):
            with torch.no_grad():
                x = (enc.to_tensor([B.to256(im) for im in ims[s:s + 16]]) - enc.mean) / enc.std
                hs = enc.dino(pixel_values=x, output_hidden_states=True).hidden_states
                out.append(torch.stack([hs[L][:, 0] for L in B.LAYERS], 1).float().cpu().numpy())
        return np.concatenate(out)

    R = {}
    for name, spec in EXTRA.items():
        f = B.OUT / f"phi_R_{name}.npz"
        if not f.exists():
            t0 = time.time(); enc.vae = ap.load_autoencoder(spec, dev); res = {}
            for k, ims in views.items():
                out = [None] * len(ims); by = {}
                for i, im in enumerate(ims):
                    by.setdefault(im.size, []).append(i)
                for idx in by.values():
                    for i, r in zip(idx, B.reconstruct(enc, [ims[i] for i in idx])):
                        out[i] = r
                res[k] = cls_layers(out)
            np.savez(f, **res); enc.vae = None
            if dev.type == "mps":
                torch.mps.empty_cache()
            print(f"{name} done in {time.time() - t0:.0f}s", flush=True)
        R[name] = dict(np.load(f))
    A, R0, names0 = B.load(); R.update({n: R0[n] for n in ("sdxl", "ftmse")})
    # are the decoders actually different? max |weight difference| of the decoders vs the E5b SDXL autoencoder
    L = ["E5b follow-up (exploratory, post hoc): SDXL decoder versions. TPR@5% / AUROC; threshold = 95th pct of matched reals.", ""]
    for g in GENS:
        L.append(g)
        for n in ["sdxl", "sdxl_base_vae", "sdxl_base_vae_1_0", "sdxl_fp16fix", "ftmse"]:
            sf, sr = B.zscore(A, R, n, f"{g}:fake", f"{g}:real"), B.zscore(A, R, n, f"{g}:real", f"{g}:real")
            L.append(f"   {n:20s} TPR {100 * (sf > np.quantile(sr, .95)).mean():5.1f}   AUROC {auroc(sf, sr):.3f}")
    txt = "\n".join(L); print(txt); (B.OUT / "sdxl_followup.txt").write_text(txt + "\n")


if __name__ == "__main__":
    main()
